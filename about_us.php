                <h2>HISTORICAL GLIMPSE</h2>
                <p>As the suburban area of Balibago, City of Santa Rosa, Laguna, slowly become more populated, the need for a Catholic School to cater to the young had arisen. The Dominican Fathers of the Holy Rosary Province, who has collaborated with the San Lorenzo Development Corporation (SLDC) and the Armed Forces of the Philippines-Retirement and Separation Benefit System (AFP-RSBS) to provide housing opportunities to the less-privileged, thought of inviting the Sisters of the Congregation of the Religious Missionaries of St. Dominic to share the mission of evangelization. The Sisters moved by their zeal for evangelization accepted the challenge. On September 1993, Rev. Fr. Bonifacio Solis, OP, Vicar of the Holy Rosary Province, in the presence of the Sisters, laid the cornerstone in a five-hectare land. This marks the post where a Catholic School Dominican College of Sta. Rosa, Laguna, Inc. would rise.</p>

                <p>At first, the Sisters wanted it to be a Catholic School exclusively for girls but the Dominican Fathers suggested that it would be of greater advantage to include boys in the mission of evangelization.</p>

